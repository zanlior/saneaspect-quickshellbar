#!/usr/bin/env python3
"""Install a reversible, isolated Hyprland module; never replace the desktop config."""
import argparse, datetime, json, os, pathlib, shlex, shutil, subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
HOME_DIR=pathlib.Path.home()
CONFIG=pathlib.Path(os.environ.get('XDG_CONFIG_HOME',HOME_DIR/'.config'))
STATE=pathlib.Path(os.environ.get('XDG_STATE_HOME',HOME_DIR/'.local/state'))/'island-shell'
MANIFEST=STATE/'installation.json'
def write_atomic(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary=path.with_name(path.name+'.island-tmp')
    try:
        temporary.write_text(text)
        if path.exists():temporary.chmod(path.stat().st_mode & 0o777)
        temporary.replace(path)
    finally:
        if temporary.exists():temporary.unlink()

def restore_files(manifest):
    for target,backup in manifest['files'].items():
        p=pathlib.Path(target)
        if backup:shutil.copy2(backup,p)
        elif p.exists():p.unlink()

def apply_install(edits):
    if MANIFEST.exists():raise SystemExit('Already installed. Use scripts/start.sh to start it; uninstall first before reinstalling.')
    stamp=datetime.datetime.now().strftime('%Y%m%d-%H%M%S-%f')
    backup_dir=STATE/('backup-'+stamp);backup_dir.mkdir(parents=True)
    manifest={'files':{},'previousLink':None,'installedText':{str(p):t for p,t in edits.items()}}
    for i,p in enumerate(edits):
        if p.exists():
            backup=backup_dir/(str(i)+'-'+p.name);shutil.copy2(p,backup);manifest['files'][str(p)]=str(backup)
        else:manifest['files'][str(p)]=None
    link=CONFIG/'quickshell/island'
    link_created=False
    try:
        for p,text in edits.items():write_atomic(p,text)
        link.parent.mkdir(parents=True,exist_ok=True)
        if link.exists() or link.is_symlink():
            previous=backup_dir/'previous-island';link.rename(previous);manifest['previousLink']=str(previous)
        link.symlink_to(ROOT,target_is_directory=True);link_created=True
        write_atomic(MANIFEST,json.dumps(manifest,indent=2)+'\n')
    except Exception:
        restore_files(manifest)
        if link_created:link.unlink()
        if manifest['previousLink']:pathlib.Path(manifest['previousLink']).rename(link)
        raise
    return backup_dir

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--apply',action='store_true');parser.add_argument('--uninstall',action='store_true');args=parser.parse_args()
    if args.uninstall:
        manifest=json.loads(MANIFEST.read_text())
        for target,text in manifest.get('installedText',{}).items():
            p=pathlib.Path(target)
            if p.exists() and p.read_text()!=text:raise SystemExit('Configuration changed since installation: '+target+'. Save your edits before restoring the backup.')
        restore_files(manifest)
        link=CONFIG/'quickshell/island'
        if link.is_symlink() and link.resolve()==ROOT:link.unlink()
        if manifest.get('previousLink'):pathlib.Path(manifest['previousLink']).rename(link)
        MANIFEST.unlink()
        subprocess.run(['quickshell','-p',str(ROOT),'kill'],capture_output=True)
        print('Previous configuration restored. Log out and back in to restart the previous bar.');return
    main_config=CONFIG/'hypr/hyprland.lua'
    autostart=CONFIG/'hypr/modules/autostart.lua'
    lua=main_config.exists()
    if not lua:main_config=CONFIG/'hypr/hyprland.conf';autostart=main_config
    if not main_config.exists():raise SystemExit('No Hyprland configuration found; see README for manual setup.')
    launcher=shlex.quote(str(ROOT/'scripts/start.sh'))
    module=CONFIG/('hypr/modules/island.lua' if lua else 'hypr/island.conf')
    if lua:
        content='-- Island shell: generated by scripts/install.py\n-- Configure shortcuts in modules/binds.lua.\n'
        content+='hl.on("hyprland.start", function() hl.exec_cmd('+json.dumps(launcher)+') end)\n'
        include='require("modules.island")'
    else:
        content='exec-once = '+launcher+'\n'
        include='source = '+str(module)
    edits={module:content}
    base=main_config.read_text()
    if include not in base:base+='\n# Island shell\n'+include+'\n' if not lua else '\n-- Island shell\n'+include+'\n'
    edits[main_config]=base
    if autostart.exists():
        src=edits.get(autostart,autostart.read_text());lines=[]
        for line in src.splitlines():
            stripped=line.lstrip()
            if not stripped.startswith(('--','#')) and ('hl.exec_cmd(' in line or stripped.startswith('exec-once')) and any(name in line for name in ('waybar','swaync')):
                line=('-- ' if lua else '# ')+'Island replaced: '+line
            lines.append(line)
        edits[autostart]='\n'.join(lines)+'\n'
    if not args.apply:
        print('Dry run. The following exact files will be written, with backups:')
        for p in edits:print(' ',p)
        print('A symlink will be created:',CONFIG/'quickshell/island','->',ROOT)
        print('Only Waybar/SwayNC autostart lines are disabled; all existing files are backed up.')
        return
    backup_dir=apply_install(edits)
    print('Installed. Backups:',backup_dir)
    print('Start with:',launcher)
    print('Undo with: python3',ROOT/'scripts/install.py','--uninstall')
if __name__=='__main__':main()
