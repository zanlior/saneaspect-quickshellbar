"""Shared palette application with rollback of files if a write fails."""
import configparser,copy,json,os,pathlib,re,shutil,signal,subprocess,tempfile,time
ROOT=pathlib.Path(__file__).resolve().parents[1]
REGISTRY=json.loads((ROOT/'themes/registry.json').read_text())
ALIASES={'tokyonight':'tokyo-night','tokyo_night':'tokyo-night'}

def command(args, **kw):
    p=subprocess.run(args,capture_output=True,text=True,timeout=30,**kw)
    if p.returncode:raise RuntimeError(p.stderr.strip() or f'{args[0]} failed')
    return p.stdout

def helper(name):
    local=pathlib.Path.home()/'.local/share/island-shell/bin'/name
    return shutil.which(name) or (str(local) if local.exists() else name)

def material_palette(wallpaper):
    if not wallpaper or not pathlib.Path(wallpaper).is_file():raise ValueError('Set a wallpaper before choosing Material You')
    raw=json.loads(command([helper('matugen'),'--dry-run','--old-json-output','--json','hex','--mode','dark','--source-color-index','0','image',str(wallpaper)]))
    colors=raw['colors']
    def c(name):
        value=colors[name]['dark']
        return value.get('color',value.get('hex')) if isinstance(value,dict) else value
    entry=copy.deepcopy(REGISTRY['material-you'])
    entry['colors']=[c('background'),c('surface_container_low'),c('surface_container_high'),c('on_background'),c('on_surface_variant'),c('primary')]
    entry['samples']=[c(n) for n in ('error','secondary','tertiary','primary','primary_fixed','secondary_fixed')]
    return entry

def kitty_colors(name,entry):
    existing=ROOT/'themes/kitty'/({'tokyo-night':'tokyo night'}.get(name,name)+'.conf')
    if name!='material-you' and existing.exists():return existing.read_text()+'\n'
    bg,panel,card,fg,muted,accent=entry['colors']
    values={'background':bg,'foreground':fg,'cursor':accent,'cursor_text_color':bg,'selection_background':accent,'selection_foreground':bg,'active_tab_background':accent,'active_tab_foreground':bg,'inactive_tab_background':panel,'inactive_tab_foreground':muted,'tab_bar_background':bg,'active_border_color':accent,'inactive_border_color':card}
    ansi=[card,*entry['samples'],fg,muted,*entry['samples'],fg]
    values.update({f'color{i}':v for i,v in enumerate(ansi)})
    return '# Generated by Island; Kitty layout and fonts are unchanged.\n'+''.join(f'{k} {v}\n' for k,v in values.items())

def atomic(path, data):
    path.parent.mkdir(parents=True,exist_ok=True)
    fd,tmp=tempfile.mkstemp(prefix='.island-',dir=path.parent)
    try:
        with os.fdopen(fd,'w') as f:f.write(data)
        os.replace(tmp,path)
    finally:
        if os.path.exists(tmp):os.unlink(tmp)

def apply(name, config, wallpaper='', reload=True):
    name=ALIASES.get(name,name)
    if name not in REGISTRY:raise ValueError('Unknown theme: '+name)
    entry=material_palette(wallpaper) if name=='material-you' else REGISTRY[name]
    if name=='material-you':
        import sys
        sys.path.insert(0,str(ROOT/'scripts/vendor'))
        import sass
        from build_themes import build
        theme_root=config/'island-shell/generated-themes'
        build(name,entry,theme_root,sass)
    else:theme_root=ROOT/'themes/gtk'
    gtk=theme_root/entry['gtk']
    if not (gtk/'gtk-4.0/gtk.css').is_file():raise RuntimeError('GTK variant has not been built: '+name)
    data_home=pathlib.Path(os.environ.get('XDG_DATA_HOME',pathlib.Path.home()/'.local/share'))
    destination=data_home/'themes'/entry['gtk']
    destination.parent.mkdir(parents=True,exist_ok=True)
    if not destination.exists() and not destination.is_symlink():destination.symlink_to(gtk,target_is_directory=True)
    elif destination.resolve()!=gtk.resolve():raise RuntimeError('Theme destination already exists: '+str(destination))
    bg,panel,card,fg,muted,accent=entry['colors']
    files={config/'kitty/colors.conf':kitty_colors(name,entry),config/'hypr/modules/island-colors.lua':f'-- Generated Island palette: {name}\nhl.config({{general={{col={{active_border="rgb({accent[1:]})", inactive_border="rgba({card[1:]}99)"}}}}}})\n'}
    for version in ('3.0','4.0'):
        settings=config/('gtk-'+version)/'settings.ini'
        ini=configparser.ConfigParser();ini.optionxform=str
        if settings.exists():ini.read(settings)
        if not ini.has_section('Settings'):ini.add_section('Settings')
        ini['Settings']['gtk-theme-name']=entry['gtk'];ini['Settings']['gtk-application-prefer-dark-theme']='0' if name=='e-ink' else '1'
        import io
        out=io.StringIO();ini.write(out);files[settings]=out.getvalue()
    # Preserve custom GTK4 rules after the managed import. Migration backs up old links.
    for filename in ('gtk.css','gtk-dark.css'):
        p=config/'gtk-4.0'/filename
        previous=p.read_text() if p.exists() and not p.is_symlink() else ''
        previous=re.sub(r'/\* Island theme begin \*/.*?/\* Island theme end \*/\n?', '',previous,flags=re.S)
        files[p]=f'/* Island theme begin */\n@import url("{(gtk/"gtk-4.0"/filename).as_uri()}");\n/* Island theme end */\n'+previous
    files[config/'island-shell/theme-state.json']=json.dumps({'name':name,'entry':entry},indent=2)+'\n'
    originals={p:('link',os.readlink(p)) if p.is_symlink() else ('file',p.read_bytes()) if p.exists() else ('missing',None) for p in files}
    try:
        for p,data in files.items():atomic(p,data)
    except Exception:
        for p,(kind,data) in originals.items():
            if p.exists() or p.is_symlink():p.unlink()
            if kind=='link':p.symlink_to(data)
            elif kind=='file':p.write_bytes(data)
        raise
    warnings=[]
    if reload:
        for args in (['gsettings','set','org.gnome.desktop.interface','gtk-theme',entry['gtk']],['gsettings','set','org.gnome.desktop.interface','color-scheme','prefer-light' if name=='e-ink' else 'prefer-dark'],['hyprctl','reload']):
            try:command(args)
            except (OSError,RuntimeError) as e:warnings.append(str(e))
        for pid in subprocess.run(['pgrep','-u',str(os.getuid()),'-x','kitty'],capture_output=True,text=True).stdout.split():
            try:os.kill(int(pid),signal.SIGUSR1)
            except ProcessLookupError:pass
    return name,entry,warnings
